#include <stdio.h>

int main()
{
    // e) Display "This is a C program." on one line.
    printf("This is a C program.\n");

    // f) Display it on two lines, first line ending with "C".
    printf("This is a C\nprogram.\n");

    // g) Display it with each word on a separate line.
    printf("This\nis\na\nC\nprogram.\n");

    // h) Display it with words separated by tabs.
    printf("This\tis\ta\tC\tprogram.\n");
    return 0;
}
